export const MANAGER_STRINGS: Record<ManagerLang, ManagerStrings> = { en, es }

export function managerStrings(lang: ManagerLang): ManagerStrings {
  return MANAGER_STRINGS[lang] ?? en
}

/** Intl locale for dates and times. */
export function localeFor(lang: ManagerLang): string {
  return lang === 'es' ? 'es-MX' : 'en-US'
}

/** date-fns locale (undefined keeps the English default). */
export function dateFnsLocale(lang: ManagerLang) {
  return lang === 'es' ? esLocale : undefined
}

/** Issue category / request kind label in the viewer's language. */
export function categoryLabelFor(id: string, type: string | undefined, lang: ManagerLang): string {
  const t = managerStrings(lang)
  const list = type === 'request' ? t.requestKind : t.category
  return list[id] ?? en.category[id] ?? id.replace(/_/g, ' ')
}

